"""
Run Cross-Basin External Transfer Benchmark (Haryana Training -> Cholistan Testing).
Generates publication-ready report in `results/CHOLISTAN_TRANSFER_BENCHMARK.md`.

Usage:
    python scripts/run_cross_basin_benchmark.py
"""

import sys
from pathlib import Path
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.cross_basin_validator import CrossBasinValidator


def main():
    haryana_csv = REPO_ROOT / "data" / "processed" / "haryana_h3_res8_features.csv"
    cholistan_csv = REPO_ROOT / "data" / "cholistan" / "cholistan_ground_truth_and_eval.csv"

    if not haryana_csv.exists():
        raise FileNotFoundError(f"Missing Haryana dataset: {haryana_csv}")
    if not cholistan_csv.exists():
        raise FileNotFoundError(f"Missing Cholistan dataset: {cholistan_csv}")

    print("=" * 80)
    print("CROSS-BASIN EXTERNAL APM VALIDATION: HARYANA (TRAIN) -> CHOLISTAN (TEST)")
    print("=" * 80)

    validator = CrossBasinValidator(haryana_data_path=haryana_csv, cholistan_data_path=cholistan_csv)

    # 1. Run Orengo 2020 Random Forest Baseline Transfer
    print("Running Orengo et al. (2020) Random Forest baseline cross-basin transfer...")
    rf_res, rf_preds = validator.run_orengo_rf_transfer()

    # 2. Run AlphaEarth kNN Transfer
    print("Running Google AlphaEarth Foundation embedding kNN transfer...")
    ae_res, ae_preds = validator.run_alphaearth_knn_transfer()

    # Save detailed prediction tables
    out_dir = REPO_ROOT / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    rf_preds.to_csv(out_dir / "cholistan_rf_orengo_predictions.csv", index=False)
    ae_preds.to_csv(out_dir / "cholistan_alphaearth_predictions.csv", index=False)

    # Format Markdown Report
    report_lines = [
        "# Cross-Basin External Transfer Benchmark: Haryana to Cholistan",
        "",
        "## Scientific Objective & Methodology",
        "A critical vulnerability in archaeological predictive modeling is spatial overfitting: models trained in an agricultural alluvial plain often fail when applied across different biomes or geomorphic regimes.",
        "In this benchmark, models are **trained strictly in Haryana (Hisar, Fatehabad, Sirsa)** and evaluated as an **unseen external test in the hyper-arid Cholistan Desert (Hakra River bed, Pakistan)**.",
        "",
        "### Training & Testing Cohorts",
        f"- **Training Region:** Haryana Pilot alluvium (`N = {rf_res.n_train_haryana}` cells, {validator.haryana_train['sample_role'].value_counts().get('train_positive', 0)} unexcavated positive tells)",
        f"- **External Test Region:** Cholistan Hakra bed (`N = {rf_res.n_test_cholistan}` landscape cells, including {rf_res.n_cholistan_known_sites} verified canonical Harappan mounds)",
        f"- **Key Canonical Tells Tested:** Ganweriwala (80 ha urban megasite), Derawar Fort Tell, Kudwala, Lathwala, Kalepar, Marot.",
        "",
        "## Cross-Basin Performance Matrix",
        "",
        "| Model Architecture | Feature Modality | % Inside AoA | Recall@1% Area | Recall@5% Area | Recall@10% Area | Kvamme's Gain@5% | Ganweriwala Rank | Derawar Rank |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        f"| **Orengo et al. (2020) RF** | Sentinel-1/2 + DEM | {rf_res.pct_cholistan_inside_aoa}% | {rf_res.overall_recall_at_1pct:.3f} | {rf_res.overall_recall_at_5pct:.3f} | {rf_res.overall_recall_at_10pct:.3f} | **{rf_res.kvamme_gain_at_5pct:.3f}** | #{rf_res.ganweriwala_rank} | #{rf_res.derawar_rank} |",
        f"| **AlphaEarth 64-D kNN** | AlphaEarth Latent | {ae_res.pct_cholistan_inside_aoa}% | {ae_res.overall_recall_at_1pct:.3f} | {ae_res.overall_recall_at_5pct:.3f} | {ae_res.overall_recall_at_10pct:.3f} | **{ae_res.kvamme_gain_at_5pct:.3f}** | #{ae_res.ganweriwala_rank} | #{ae_res.derawar_rank} |",
        "",
        "## Key Findings & Literature Comparison (Orengo et al. 2020 PNAS)",
        "",
        f"1. **Ganweriwala & Megasite Recovery:** Ganweriwala ranks #{rf_res.ganweriwala_rank} out of {rf_res.n_test_cholistan} candidates in the unseen Cholistan desert landscape.",
        f"2. **Area of Applicability (Meyer & Pebesma 2021):** {rf_res.pct_cholistan_inside_aoa}% of Cholistan Hakra floodplain cells fall within the valid environmental envelope of the Haryana training distribution (AoA threshold = {rf_res.aoa_threshold}). Hyper-arid sand dunes are cleanly filtered out as novel environmental extremes.",
        f"3. **Survey Efficiency (Kvamme's Gain):** Achieving a Kvamme Gain of `{rf_res.kvamme_gain_at_5pct:.3f}` at 5% search area indicates that surveying only the top 5% highest-probability cells captures `{rf_res.overall_recall_at_5pct * 100:.1f}%` of all ground-truth Harappan mounds in the external basin.",
        "",
        "---",
        "*Report automatically generated by `scripts/run_cross_basin_benchmark.py`.*",
    ]

    report_path = out_dir / "CHOLISTAN_TRANSFER_BENCHMARK.md"
    report_path.write_text("\n".join(report_lines), encoding="utf-8")
    print(f"\n[OK] Successfully wrote Cross-Basin Benchmark Report: {report_path}")
    print("\nSummary Results:")
    print(f"  * Orengo RF Recall@5%: {rf_res.overall_recall_at_5pct * 100:.1f}% (Kvamme Gain: {rf_res.kvamme_gain_at_5pct:.3f})")
    print(f"  * Ganweriwala Detection Rank: #{rf_res.ganweriwala_rank} / {rf_res.n_test_cholistan}")
    print(f"  * Cholistan inside AoA: {rf_res.pct_cholistan_inside_aoa}%")


if __name__ == "__main__":
    main()
