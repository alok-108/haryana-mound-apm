class SubcontinentKnownMonumentsRegistry:
    """
    Spatial exclusion registry that indexes all documented Pre-600 BCE monuments.
    Guarantees candidate discoveries are strictly unexcavated and undiscovered.
    """

    def __init__(self, min_exclusion_distance_m: float = 1500.0) -> None:
        self.min_exclusion_distance_m = min_exclusion_distance_m
        self.monuments = KNOWN_MONUMENTS_REGISTRY
        pts_3d = [latlon_to_cartesian_3d(m.latitude, m.longitude) for m in self.monuments]
        self.kd_tree_3d = cKDTree(np.array(pts_3d, dtype=np.float64))

    def query_nearest_known_monument(
        self, lat: float, lon: float
    ) -> Tuple[float, KnownMonument]:
        """Query nearest known monument and surface distance in meters."""
        q_3d = latlon_to_cartesian_3d(lat, lon)
        chord_dist, idx = self.kd_tree_3d.query(q_3d, k=1)
        arc_dist_m = float(chord_distance_to_arc_distance_m(chord_dist))
        return arc_dist_m, self.monuments[idx]

    def verify_is_undiscovered(
        self, lat: float, lon: float
    ) -> Tuple[bool, float, KnownMonument]:
        """
        Verify that coordinates represent an unrecorded, undiscovered site.
        Returns: (is_novel, distance_to_nearest_m, nearest_monument).
        """
        dist_m, nearest = self.query_nearest_known_monument(lat, lon)
        is_novel = dist_m >= self.min_exclusion_distance_m
        return is_novel, dist_m, nearest

    def to_dataframe(self) -> pd.DataFrame:
        """Convert registry to pandas DataFrame for inspection and reporting."""
        return pd.DataFrame([asdict(m) for m in self.monuments])
